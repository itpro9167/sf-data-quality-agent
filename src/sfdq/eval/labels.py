"""Labeled expected fixes for the seeded mock org.

Every label says what a careful human analyst would do about one seeded problem, derived from the
generator's *ground truth* (the correct value before it was corrupted), not from the output of any
scanner or agent. So the eval measures the agent against reality rather than against itself.

Each fixable label carries a ``difficulty``:

* ``mechanical``: the fix follows from the bad value alone (trim, collapse ``@@``, strip a trailing
  dash, fix a known email-domain typo, re-case a postal code);
* ``needs_context``: the fix needs other data (a dropped leading zero needs the state; a missing
  ``.com`` or ``@`` needs the Account's website; a duplicate needs the records compared);
* ``judgment``: the data alone cannot say, so the right move is *flag for owner review*.

The committed ``data/expected_fixes.json`` is generated by :func:`build_labels`; a test fails if it
drifts from the generator. Regenerate with ``python -m sfdq.eval --write-labels``.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from dataclasses import asdict
from importlib import resources
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, Field

from sfdq.models import ActionType, Finding, FindingKind, ObjectType, Record
from sfdq.salesforce.mock_data import LEADING_ZERO_STATES, MockOrgData, generate_mock_org

Difficulty = Literal["mechanical", "needs_context", "judgment"]

_TYPO_DOMAINS = {"gmial.com": "gmail.com", "hotmial.com": "hotmail.com", "gmaill.com": "gmail.com"}
_COMPLETENESS = {
    "Account": ["Name", "Website", "Phone", "Industry", "BillingCity", "BillingPostalCode",
                "BillingCountry", "Description"],
    "Contact": ["FirstName", "LastName", "Email", "Phone", "MobilePhone", "Title", "AccountId",
                "MailingPostalCode"],
}  # fmt: skip
_KIND_ORDER = {k: i for i, k in enumerate(FindingKind)}


class ExpectedFix(BaseModel):
    """What should happen for one seeded problem."""

    id: str
    issue_type: FindingKind
    object_type: ObjectType
    record_ids: list[str] = Field(min_length=1)
    expected_action: ActionType
    difficulty: Difficulty
    field: str | None = None
    expected_changes: dict[str, str] = Field(default_factory=dict)
    acceptable_survivors: list[str] = Field(default_factory=list)
    rationale: str

    @property
    def auto_fix(self) -> bool:
        """True when the right answer is an automated fix (merge or update) rather than a flag."""
        return self.expected_action in (ActionType.MERGE, ActionType.UPDATE_FIELD)


class NegativeControl(BaseModel):
    """Records that look like a problem but are not (must NOT be reported)."""

    issue_type: FindingKind
    object_type: ObjectType
    record_ids: list[str]
    note: str


class LabelSet(BaseModel):
    """A complete labeled dataset for one generated org."""

    version: int = 1
    seed: int
    org_fingerprint: str | None = None  # hash of the seeded ground truth these labels describe
    description: str
    fixes: list[ExpectedFix]
    negative_controls: list[NegativeControl] = Field(default_factory=list)


def org_fingerprint(org: MockOrgData) -> str:
    """Hash of the seeded problems and their ground truth: changes if the generator changes."""
    blob = json.dumps(asdict(org.seeded), sort_keys=True, default=str)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def label_key(fix: ExpectedFix) -> tuple[str, str, frozenset[str], str | None]:
    """Identity used to match a label to the scanner finding for the same problem."""
    return (fix.issue_type.value, fix.object_type, frozenset(fix.record_ids), fix.field)


def finding_key(f: Finding) -> tuple[str, str, frozenset[str], str | None]:
    """Same identity, computed from a scanner finding."""
    field = f.details.get("field") if f.kind is FindingKind.INVALID_FORMAT else None
    return (f.kind.value, f.object_type, frozenset(f.record_ids), field)


# --------------------------------------------------------------------------------------------
# Label construction
# --------------------------------------------------------------------------------------------
def _domain(value: str | None) -> str | None:
    if not value:
        return None
    host = re.sub(r"^[a-z]+://", "", value.strip().lower()).split("/")[0]
    return re.sub(r"^www\.", "", host) or None


def _classify_format(
    fld: str,
    corrupted: str,
    truth: str,
    record: Record,
    account_domain: str | None,
) -> Difficulty:
    """How hard is it to restore ``truth`` from ``corrupted`` (and its context)?"""
    if corrupted.strip() == truth:
        return "mechanical"
    if "Email" in fld:
        if corrupted.replace("@@", "@") == truth:
            return "mechanical"
        local, _, dom = corrupted.rpartition("@")
        if (
            local
            and _TYPO_DOMAINS.get(dom.lower())
            and f"{local}@{_TYPO_DOMAINS[dom.lower()]}" == truth
        ):
            return "mechanical"
        if account_domain and truth.endswith("@" + account_domain):
            return "needs_context"  # restorable from the Account's website domain
        return "judgment"
    if "PostalCode" in fld:
        if corrupted.strip().rstrip("-") == truth:
            return "mechanical"
        squashed = re.sub(r"\s+", "", corrupted.upper())
        if squashed == re.sub(r"\s+", "", truth.upper()):
            return "mechanical"  # e.g. 'm5v2t6' -> 'M5V 2T6'
        state = record.get("BillingState") or record.get("MailingState")
        if (
            truth.startswith("0")
            and corrupted == truth.lstrip("0")
            and state in LEADING_ZERO_STATES
        ):
            return "needs_context"  # a dropped leading zero, given the state
        return "judgment"
    return "judgment"  # phone numbers: only whitespace is mechanical (handled above)


def build_labels(org: MockOrgData) -> LabelSet:
    """Derive expected fixes from the generator's seeded problems and ground truth."""
    seeded = org.seeded
    accounts = {r["Id"]: r for r in org.records["Account"]}
    contacts = {r["Id"]: r for r in org.records["Contact"]}
    by_obj = {"Account": accounts, "Contact": contacts}
    fixes: list[ExpectedFix] = []

    def pristine(rid: str, fld: str, record: Record) -> object:
        return seeded.truth.get(f"{rid}:{fld}", record.get(fld))

    # -- duplicates: merge, keeping any of the most complete records ---------------------------
    for obj, clusters in seeded.duplicate_clusters.items():
        for ids in clusters:
            recs = {i: by_obj[obj][i] for i in ids}
            score = {i: sum(bool(r.get(f)) for f in _COMPLETENESS[obj]) for i, r in recs.items()}
            best = max(score.values())
            fixes.append(
                ExpectedFix(
                    id=f"duplicate:{obj}:{sorted(ids)[0]}",
                    issue_type=FindingKind.DUPLICATE,
                    object_type=obj,
                    record_ids=sorted(ids),
                    expected_action=ActionType.MERGE,
                    difficulty="needs_context",
                    acceptable_survivors=sorted(i for i, sc in score.items() if sc == best),
                    rationale="Seeded duplicate: keep the most complete record, merge the rest.",
                )
            )

    # -- invalid formats -----------------------------------------------------------------------
    for obj, items in seeded.invalid_formats.items():
        for rid, fld in items:
            rec = by_obj[obj][rid]
            truth = str(seeded.truth[f"{rid}:{fld}"])
            account_id = rec.get("AccountId") if obj == "Contact" else rid
            account = accounts.get(account_id) if account_id else None
            acct_domain = (
                _domain(str(pristine(account["Id"], "Website", account))) if account else None
            )
            difficulty = _classify_format(fld, str(rec[fld]), truth, rec, acct_domain)
            fixable = difficulty != "judgment"
            fixes.append(
                ExpectedFix(
                    id=f"invalid_format:{obj}:{rid}:{fld}",
                    issue_type=FindingKind.INVALID_FORMAT,
                    object_type=obj,
                    record_ids=[rid],
                    field=fld,
                    expected_action=ActionType.UPDATE_FIELD
                    if fixable
                    else ActionType.FLAG_FOR_REVIEW,
                    difficulty=difficulty,
                    expected_changes={fld: truth} if fixable else {},
                    rationale=(
                        f"The correct value ({truth!r}) can be restored ({difficulty})."
                        if fixable
                        else "The correct value cannot be recovered from the data; ask the owner."
                    ),
                )
            )

    # -- missing fields ------------------------------------------------------------------------
    for obj, gaps in seeded.missing_fields.items():
        for rid, missing in gaps.items():
            expected: dict[str, str] = {}
            if obj == "Account" and "Website" in missing:
                want = _domain(str(seeded.truth[f"{rid}:Website"]))
                emails = [
                    str(c["Email"]).rsplit("@", 1)[-1].lower()
                    for c in contacts.values()
                    if c["AccountId"] == rid and c.get("Email") and "@" in str(c["Email"])
                ]
                if want and want in emails:
                    expected = {"Website": want}  # compared by domain
            fixes.append(
                ExpectedFix(
                    id=f"missing_fields:{obj}:{rid}",
                    issue_type=FindingKind.MISSING_FIELDS,
                    object_type=obj,
                    record_ids=[rid],
                    expected_action=ActionType.UPDATE_FIELD
                    if expected
                    else ActionType.FLAG_FOR_REVIEW,
                    difficulty="needs_context" if expected else "judgment",
                    expected_changes=expected,
                    rationale=(
                        "Website is inferable from the contacts' shared corporate email domain."
                        if expected
                        else f"Missing {', '.join(missing)} cannot be derived; ask the owner."
                    ),
                )
            )

    # -- stale: never auto-fix; the owner decides ----------------------------------------------
    for obj, ids in seeded.stale.items():
        for rid in ids:
            fixes.append(
                ExpectedFix(
                    id=f"stale:{obj}:{rid}",
                    issue_type=FindingKind.STALE,
                    object_type=obj,
                    record_ids=[rid],
                    expected_action=ActionType.FLAG_FOR_REVIEW,
                    difficulty="judgment",
                    rationale="Only the record owner knows whether it is still active.",
                )
            )

    fixes.sort(key=lambda f: (_KIND_ORDER[f.issue_type], f.object_type, f.id))
    controls = [
        NegativeControl(
            issue_type=FindingKind.DUPLICATE,
            object_type=obj,
            record_ids=ids,
            note="Looks similar (same name / same prefix and city) but is a different entity.",
        )
        for obj, pairs in seeded.decoys.items()
        for ids in pairs
    ]
    return LabelSet(
        seed=org.seed,
        org_fingerprint=org_fingerprint(org),
        description=(
            "Expected fixes for the seeded mock org (sfdq.salesforce.mock_data, seed "
            f"{org.seed}), derived from the generator's ground truth."
        ),
        fixes=fixes,
        negative_controls=controls,
    )


# --------------------------------------------------------------------------------------------
# Loading / writing
# --------------------------------------------------------------------------------------------
def default_labels_text() -> str:
    """Text of the bundled labels file."""
    return resources.files("sfdq.eval").joinpath("data/expected_fixes.json").read_text("utf-8")


def load_labels(path: Path | None = None) -> LabelSet:
    """Load labels from ``path`` or the bundled file."""
    text = path.read_text("utf-8") if path else default_labels_text()
    return LabelSet.model_validate_json(text)


def dump_labels(labels: LabelSet) -> str:
    """Stable JSON for the committed file."""
    return json.dumps(labels.model_dump(mode="json"), indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    """``python -m sfdq.eval [--write-labels]``: print or regenerate the bundled labels."""
    args = sys.argv[1:] if argv is None else argv
    text = dump_labels(build_labels(generate_mock_org(seed=42)))
    if "--write-labels" in args:
        target = Path(__file__).parent / "data" / "expected_fixes.json"
        target.write_text(text, "utf-8")
        print(f"wrote {target}")
    else:
        print(text)
    return 0
